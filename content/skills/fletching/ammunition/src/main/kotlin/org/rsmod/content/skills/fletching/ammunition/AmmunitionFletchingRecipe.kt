public enum class AmmunitionFamily(
    public val batchSize: Int,
    public val alwaysMakeX: Boolean,
    public val usesOptionalMakeX: Boolean = false,
) {
    Atlatl(batchSize = 20, alwaysMakeX = true),
    HeadlessArrow(batchSize = 15, alwaysMakeX = true),
    Arrow(batchSize = 15, alwaysMakeX = true),
    Bolt(batchSize = 10, alwaysMakeX = false, usesOptionalMakeX = true),
    TippedBolt(batchSize = 10, alwaysMakeX = false, usesOptionalMakeX = true),
    Dart(batchSize = 10, alwaysMakeX = false, usesOptionalMakeX = true),
    Javelin(batchSize = 15, alwaysMakeX = true),
    FlightedOgreArrow(batchSize = 6, alwaysMakeX = false),
    OgreArrow(batchSize = 6, alwaysMakeX = false),
    BrutalArrow(batchSize = 6, alwaysMakeX = false),
}

