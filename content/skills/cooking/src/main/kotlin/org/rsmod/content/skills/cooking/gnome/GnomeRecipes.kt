public fun g(name: String): ObjType = GnomeCookingObjs[name]

public data class GnomeMaterial(val obj: ObjType, val count: Int = 1)

public enum class GnomeMould(
    val containerName: String,
    val rawName: String,
    val halfName: String,
    val burntName: String,
) {
    Crunchy("crunchy_tray", "raw_crunchies", "half_baked_crunchy", "burnt_crunchies"),
    Batta("batta_tin", "raw_batta", "half_baked_batta", "burnt_batta"),
    Bowl("gnomebowl_mould", "raw_gnomebowl", "half_baked_bowl", "burnt_gnomebowl");

    public val container: ObjType
        get() = g(containerName)

    public val raw: ObjType
        get() = g(rawName)

    public val half: ObjType
        get() = g(halfName)

    public val burnt: ObjType
        get() = g(burntName)
}

public data class GnomeDish(
    val name: String,
    val mould: GnomeMould,
    val prepared: ObjType,
    val baked: ObjType,
    val result: ObjType,
    val level: Int,
    val prepXp: Double,
    val finishXp: Double,
    val ingredients: List<GnomeMaterial>,
    val spice: Boolean,
    val garnish: List<GnomeMaterial>,
    val garnishSpice: Boolean,
) {
    public val finishesBaked: Boolean
        get() = baked == result
}

public data class GnomeCocktail(
    val name: String,
    val mixed: ObjType,
    val result: ObjType,
    val level: Int,
    val finishXp: Double,
    val ingredients: List<GnomeMaterial>,
    val garnish: List<GnomeMaterial>,
)

