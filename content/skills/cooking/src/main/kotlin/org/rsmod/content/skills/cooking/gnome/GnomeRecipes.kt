    public fun finishesByBaking(output: ObjType): Boolean =
        dishes.any { it.finishesBaked && it.result == output } || output == g("drunk_dragon")

    private fun bake(
        raw: ObjType,
        cooked: ObjType,
        burnt: ObjType?,
        level: Int,
        xp: Double,
        container: ObjType? = null,
        always: Boolean = false,
        first: Int = 4,
    ) =
        StandardCookingRecipe(
            raw,
            cooked,
            burnt,
            level,
            xp,
            true,
            CookingChance(118, 492),
            hosidius = CookingChance(130, 504),
            hosidiusElite = CookingChance(143, 517),
            alwaysSucceeds = always,
            firstResultTicks = first,
            secondResultGapTicks = if (first == 4) 4 else 3,
            repeatResultGapTicks = 4,
            returnedContainer = container,
            returnedContainerOnSuccessOnly = true,
            allowedSources =
                setOf(
                    CookingSourceKind.Range,
                    CookingSourceKind.Lumbridge,
                    CookingSourceKind.Hosidius,
                ),
        )
}
